import { useState } from 'react'
import { ChevronDown, ChevronRight, Copy, Download, Smartphone } from 'lucide-react'
import { useUI } from '../../../store/ui'
import { defaultsOf, fromCustom, type Command, type Vals } from './catalog'
import { Customize } from './Customize'
import { Library } from './Library'
import { useCommanderData } from './useCommanderData'

/**
 * The command library + customize pane as one embeddable block. In `terminal` mode the chosen
 * command is sent to the page's terminal; in `mosh` mode it is wrapped into a mosh invocation to
 * copy, download or hand to Termux (mosh cannot run inside the browser).
 */
interface Props {
  profile: string
  mode: 'terminal' | 'mosh'
  onRun?: (line: string, cmd: Command | null) => void
  onPaste?: (line: string) => void
  /** mosh mode: wrap a shell line into the mosh command that runs it. */
  wrap?: (line: string) => string
  title?: string
  defaultOpen?: boolean
}

export function SnippetDeck({ profile, mode, onRun, onPaste, wrap, title, defaultOpen = true }: Props) {
  const notify = useUI((s) => s.notify)
  const { commands, favorites, recent, toggleFavorite, remember, saveCustom, deleteCustom, data } = useCommanderData()
  const [open, setOpen] = useState(defaultOpen)
  const [selected, setSelected] = useState<Command | null>(null)
  const [vals, setVals] = useState<Vals>({})
  const select = (c: Command) => {
    setSelected(c)
    setVals(defaultsOf(c))
  }
  const wrapped = (line: string) => (wrap ? wrap(line) : line)
  const run = (line: string, cmd: Command | null = selected) => {
    if (cmd?.ftp) return notify('That is an FTP action: use it in the Filesystem commander', 'error')
    if (cmd?.risk === 'danger' && mode === 'terminal' && !window.confirm(`This is marked dangerous:\n\n${line}\n\nRun it?`)) return
    if (mode === 'terminal') onRun?.(line, cmd)
    else navigator.clipboard.writeText(wrapped(line)).then(() => notify('mosh command copied: paste it in your terminal app', 'success'))
    remember(cmd, mode === 'terminal' ? line : wrapped(line), mode)
  }
  const download = () => {
    if (!selected) return
    const line = wrapped(selected.build(vals))
    const blob = new Blob([`#!/usr/bin/env bash\n# ${selected.name} · generated by the xGallery developer panel\n${line}\n`], { type: 'text/x-shellscript' })
    const a = document.createElement('a')
    a.href = URL.createObjectURL(blob)
    a.download = `${selected.id}.sh`
    a.click()
    URL.revokeObjectURL(a.href)
  }
  const termux = () => {
    if (!selected) return
    const ok = window.NativeSsh?.openTermux(wrapped(selected.build(vals)))
    notify(ok ? 'Handed over to Termux' : 'Termux is not installed (get it from F-Droid)', ok ? 'success' : 'error')
  }
  return (
    <section className="card stack snippet-deck" style={{ gap: 8 }} data-snippet-deck={mode}>
      <button className="row" style={{ gap: 6, background: 'none', border: 0, color: 'inherit', font: 'inherit', cursor: 'pointer', padding: 0 }} onClick={() => setOpen(!open)} aria-expanded={open}>
        {open ? <ChevronDown size={14} /> : <ChevronRight size={14} />}
        <h3 style={{ margin: 0 }}>{title ?? (mode === 'mosh' ? 'Mosh snippets' : 'Snippets')}</h3>
        <span className="muted small">{commands.length} commands · {mode === 'terminal' ? 'click to customise, Run sends it to the active terminal' : 'click to customise, then copy the mosh command, download it or open Termux'}</span>
      </button>
      {open && (
        <div className="snippet-deck-body">
          <Library commands={commands} favorites={favorites} recent={recent} selectedId={selected?.id ?? null} onSelect={select} onRun={(c) => { select(c); run(c.build(defaultsOf(c)), c) }} onFavorite={toggleFavorite} />
          <div className="stack" style={{ gap: 8, minWidth: 0 }}>
            <Customize cmd={selected} vals={vals} setVals={setVals} profile={profile} favorite={!!selected && favorites.has(selected.id)} onFavorite={() => selected && toggleFavorite(selected.id)} onRun={(line) => run(line)} onPaste={(line) => (mode === 'terminal' ? onPaste?.(line) : navigator.clipboard.writeText(line).then(() => notify('Copied', 'success')))} onSaveCustom={(cs) => { saveCustom(cs); select(fromCustom(cs)); notify(`Snippet “${cs.name}” saved`, 'success') }} onDeleteCustom={(id) => { deleteCustom(id); setSelected(null) }} customs={data.customs} runLabel={mode === 'mosh' ? 'Copy mosh command' : undefined} pasteLabel={mode === 'mosh' ? 'Copy bare command' : undefined} />
            {mode === 'mosh' && selected && !selected.ftp && (
              <div className="card stack" style={{ gap: 6 }}>
                <span className="eyebrow">As a mosh session</span>
                <pre className="vps-pre" style={{ maxHeight: 140 }} data-mosh-preview="">{wrapped(selected.build(vals))}</pre>
                <div className="row" style={{ gap: 4 }}>
                  <button className="btn sm" onClick={() => navigator.clipboard.writeText(wrapped(selected.build(vals))).then(() => notify('Copied', 'success'))}>
                    <Copy size={12} /> Copy
                  </button>
                  <button className="btn sm" onClick={download}>
                    <Download size={12} /> Download .sh
                  </button>
                  <button className="btn sm" onClick={termux} title="Needs the Android developer-panel app with Termux installed">
                    <Smartphone size={12} /> Open in Termux
                  </button>
                </div>
                <p className="muted small" style={{ margin: 0 }}>mosh keeps the session alive across network changes; the command runs in a login shell on the server and the session stays open afterwards.</p>
              </div>
            )}
          </div>
        </div>
      )}
    </section>
  )
}
