import { useState } from 'react'
import { Check, Copy, Download, Eye, EyeOff } from 'lucide-react'
import { useUI } from '../../../store/ui'

/** A shell snippet with copy, download-as-script and secret masking. */
export function CommandBlock({ title, code, filename, hint, mask }: { title?: string; code: string; filename?: string; hint?: string; mask?: string[] }) {
  const notify = useUI((s) => s.notify)
  const [copied, setCopied] = useState(false)
  const [reveal, setReveal] = useState(false)
  const secrets = (mask ?? []).filter(Boolean)
  const shown = reveal || !secrets.length ? code : secrets.reduce((acc, s) => acc.split(s).join('••••••••'), code)
  const copy = () => navigator.clipboard.writeText(code).then(() => { setCopied(true); notify('Copied to the clipboard', 'success'); setTimeout(() => setCopied(false), 1500) })
  const download = () => {
    const blob = new Blob([`#!/usr/bin/env bash\n# generated by the xGallery developer panel\n${code}\n`], { type: 'text/x-shellscript' })
    const a = document.createElement('a')
    a.href = URL.createObjectURL(blob)
    a.download = filename ?? 'xgallery-ops.sh'
    a.click()
    URL.revokeObjectURL(a.href)
  }
  return (
    <div className="cmd-block" data-cmd={title ?? ''}>
      <div className="cmd-head">
        <strong>{title}</strong>
        {hint && <span className="muted small">{hint}</span>}
        <span className="grow" />
        {secrets.length > 0 && (
          <button className="btn ghost sm" onClick={() => setReveal((v) => !v)} title={reveal ? 'Hide secrets' : 'Show secrets'}>
            {reveal ? <EyeOff size={12} /> : <Eye size={12} />}
          </button>
        )}
        <button className="btn ghost sm" onClick={download} title="Download as .sh">
          <Download size={12} />
        </button>
        <button className="btn sm" onClick={copy}>
          {copied ? <Check size={12} /> : <Copy size={12} />} Copy
        </button>
      </div>
      <pre className="cmd-code">{shown}</pre>
    </div>
  )
}
